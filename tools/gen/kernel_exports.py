"""Generate recomp/runtime/host/kernel_exports.inc from third_party/nxdk/xboxkrnl.exe.def.

Usage: python3 tools/gen/kernel_exports.py"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
rows = []
for line in (ROOT / "third_party/nxdk/xboxkrnl.exe.def").read_text().splitlines():
    m = re.match(r"\s*(@?)(\w+?)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?", line)
    if m:
        fastcall, name, args, ordinal, data = m.groups()
        rows.append((int(ordinal), name, int(args or 0), bool(data), bool(fastcall)))
rows.sort()
out = ["// Generated by tools/gen/kernel_exports.py from third_party/nxdk/xboxkrnl.exe.def (CC0). Do not edit.",
       "// {ordinal, name, stdcall argument bytes, data export, fastcall}"]
out += [f'{{{o}, "{n}", {a}, {"true" if d else "false"}, {"true" if f else "false"}}},' for o, n, a, d, f in rows]
(ROOT / "recomp/runtime/host/kernel_exports.inc").write_text("\n".join(out) + "\n")
print(len(rows), "exports")
