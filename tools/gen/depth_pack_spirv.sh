#!/bin/sh
# Compiles recomp/runtime/gfx/depth/depth_pack.glsl (a depth target packed as
# the console's D24S8 words, for draws that read one as a texture) to SPIR-V,
# into recomp/runtime/gfx/depth/depth_pack_spirv.inc, which is committed: the
# runtime builds no shaders. Needs glslangValidator and spirv-val. Run from
# the repository's root after changing the shader.
set -eu
src=recomp/runtime/gfx/depth/depth_pack.glsl
out=recomp/runtime/gfx/depth/depth_pack_spirv.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/gen/depth_pack_spirv.sh from depth_pack.glsl; don't edit."
    for stage in vert frag; do
        if [ "$stage" = vert ]; then kind=-DVERTEX; else kind=-DFRAGMENT; fi
        glslangValidator -V --target-env vulkan1.3 $kind -S "$stage" -o "$tmp/s.spv" "$src" >/dev/null
        spirv-val --target-env vulkan1.3 "$tmp/s.spv"
        echo "inline constexpr uint32_t kDepthPack_${stage}[] = {"
        od -An -v -tx4 "$tmp/s.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
        echo "};"
    done
} > "$out"
echo "wrote $out"
