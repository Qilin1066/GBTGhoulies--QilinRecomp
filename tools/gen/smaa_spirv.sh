#!/bin/sh
# Compiles the SMAA shaders (recomp/runtime/gfx/smaa/smaa.glsl, over
# third_party/smaa) to SPIR-V, into recomp/runtime/gfx/smaa/smaa_spirv.inc,
# which is committed: the runtime builds no shaders. Needs glslangValidator
# and spirv-val. Run from the repository's root after changing either.
set -eu
src=recomp/runtime/gfx/smaa/smaa.glsl
out=recomp/runtime/gfx/smaa/smaa_spirv.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/gen/smaa_spirv.sh from smaa.glsl and third_party/smaa (MIT); don't edit."
    for pass in 1 2 3; do
        for stage in vert frag; do
            if [ "$stage" = vert ]; then kind=-DVERTEX; else kind=-DFRAGMENT; fi
            glslangValidator -V --target-env vulkan1.3 -DPASS=$pass $kind -S "$stage" -o "$tmp/s.spv" "$src" >/dev/null
            spirv-val --target-env vulkan1.3 "$tmp/s.spv"
            echo "inline constexpr uint32_t kSmaa${pass}_${stage}[] = {"
            od -An -v -tx4 "$tmp/s.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
            echo "};"
        done
    done
} > "$out"
echo "wrote $out"
