#!/bin/sh
# Compiles the FSR 1 compute shaders (recomp/runtime/gfx/fsr/fsr.comp, over
# third_party/fsr1) to SPIR-V, into recomp/runtime/gfx/fsr/fsr_spirv.inc, which
# is committed: the runtime builds no shaders. Needs glslangValidator and
# spirv-val (the Vulkan SDK, or a distribution's glslang-tools and
# spirv-tools). Run from the repository's root after changing either.
set -eu
src=recomp/runtime/gfx/fsr/fsr.comp
out=recomp/runtime/gfx/fsr/fsr_spirv.inc
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
    echo "// Generated by tools/gen/fsr_spirv.sh from fsr.comp and third_party/fsr1 (MIT); don't edit."
    for pass in EASU RCAS; do
        glslangValidator -V --target-env vulkan1.3 -D"$pass" -S comp -o "$tmp/$pass.spv" "$src" >/dev/null
        spirv-val --target-env vulkan1.3 "$tmp/$pass.spv"
        lower=$(echo "$pass" | tr 'A-Z' 'a-z')
        echo "inline constexpr uint32_t kFsr_${lower}[] = {"
        od -An -v -tx4 "$tmp/$pass.spv" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
        echo "};"
    done
} > "$out"
echo "wrote $out"
