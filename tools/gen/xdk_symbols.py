"""Generate recomp/runtime/host/xdk_symbols.inc: names for the XDK library
functions and variables in the game's XBE, found by signature.

The names come from XbSymbolDatabase (MIT, https://github.com/Cxbx-Reloaded/XbSymbolDatabase),
which scans an XBE for the XDK libraries' functions. Build its command-line
tool, then:

    python3 tools/gen/xdk_symbols.py path/to/XbSymbolDatabaseCLI path/to/default.xbe

The output lists addresses in this game's XBE (the USA release) with the names
of the Microsoft library symbols found there; it holds no game code or data."""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if len(sys.argv) != 3:
    sys.exit(__doc__)
text = subprocess.run([sys.argv[1], sys.argv[2]], check=True, capture_output=True, text=True).stdout
rows = []
for line in text.splitlines():
    m = re.fullmatch(r"(\w+?)__(\w+) = 0x([0-9a-fA-F]+)", line.strip())
    # "_OFFSET" symbols and values below the image base are offsets, not addresses.
    if m and not m.group(2).endswith("_OFFSET") and int(m.group(3), 16) >= 0x10000:
        rows.append((int(m.group(3), 16), m.group(1), m.group(2)))
rows.sort()
out = ["// Generated by tools/gen/xdk_symbols.py with XbSymbolDatabase (MIT). Do not edit.",
       "// {address in the USA release's default.xbe, XDK library, symbol}"]
out += [f'{{0x{a:08X}, "{lib}", "{name}"}},' for a, lib, name in rows]
(ROOT / "recomp/runtime/host/xdk_symbols.inc").write_text("\n".join(out) + "\n")
print(len(rows), "symbols")
